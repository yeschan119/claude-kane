def read_settings():
    try:
        return json.loads(SETTINGS_PATH.read_text())
    except FileNotFoundError:
        return {}
    except ValueError as error:
        raise SystemExit(f"x {SETTINGS_PATH} is not valid JSON ({error}) — fix it first; nothing was changed")


def write_settings(settings):
    SETTINGS_PATH.parent.mkdir(parents=True, exist_ok=True)
    SETTINGS_PATH.write_text(json.dumps(settings, indent=2, ensure_ascii=False) + "\n")


def is_kane_on(settings):
    return settings.get("statusLine") == KANE_STATUSLINE


def turn_on():
    settings = read_settings()
    KANE_DIR.mkdir(parents=True, exist_ok=True)
    LAUNCHER_PATH.write_text(LAUNCHER_SOURCE)
    if is_kane_on(settings):
        print(f"kane HUD already on — launcher refreshed: {LAUNCHER_PATH}")
        return
    BACKUP_PATH.write_text(json.dumps({"statusLine": settings.get("statusLine")}, indent=2, ensure_ascii=False) + "\n")
    settings["statusLine"] = KANE_STATUSLINE
    write_settings(settings)
    print(f"kane HUD on — previous statusLine backed up to {BACKUP_PATH}. Shows from the next statusline refresh.")


def turn_off():
    settings = read_settings()
    if not is_kane_on(settings):
        print("kane HUD is not on — settings.json unchanged")
        return
    try:
        previous = json.loads(BACKUP_PATH.read_text()).get("statusLine")
    except (OSError, ValueError):
        previous = None
    if previous is None:
        settings.pop("statusLine", None)
    else:
        settings["statusLine"] = previous
    write_settings(settings)
    BACKUP_PATH.unlink(missing_ok=True)
    print("kane HUD off — " + ("previous statusLine restored" if previous else "statusLine removed (none before)"))


def print_status():
    settings = read_settings()
    if is_kane_on(settings):
        print(f"kane HUD on — {KANE_STATUSLINE['command']}")
    else:
        current = (settings.get("statusLine") or {}).get("command")
        print("kane HUD off — current statusLine: " + (current or "none"))


def main(argv):
    action = argv[0] if argv else "status"
    actions = {"on": turn_on, "off": turn_off, "status": print_status}
    if action not in actions:
        raise SystemExit(__doc__)
    actions[action]()


if __name__ == "__main__":
    main(sys.argv[1:])
